"""BotShield Report Generation Engine

Generates structured JSON exports and professional PDF reports using ReportLab,
incorporating severity badges, findings breakdowns, and compliance disclaimers.
"""

from datetime import datetime
import io
import json
from pathlib import Path
from typing import Any, Dict, Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.config import settings


def generate_json_report(data: Dict[str, Any]) -> str:
    """Serializes scan or intelligence findings into formatted JSON."""
    payload = {
        "generator": "BotShield Security Platform",
        "version": settings.app_version,
        "exported_at": datetime.utcnow().isoformat() + "Z",
        "report_data": data,
        "disclaimer": (
            "This report is generated by BotShield for defensive security auditing. "
            "It reflects non-invasive passive observation and does not replace manual penetration testing."
        )
    }
    return json.dumps(payload, indent=2)


def generate_pdf_report(
    title: str,
    target: str,
    category: str,
    score: int,
    findings: list,
    metadata: Dict[str, Any]
) -> bytes:
    """Generates an executive-style PDF security report in bytes."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40,
    )

    styles = getSampleStyleSheet()

    # Custom Cyber Palette
    c_navy = colors.HexColor("#0f172a")
    c_cyan = colors.HexColor("#0284c7")
    c_slate = colors.HexColor("#475569")
    c_bg_card = colors.HexColor("#f8fafc")

    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=22,
        textColor=c_navy,
        spaceAfter=4,
    )

    subtitle_style = ParagraphStyle(
        "DocSub",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=12,
        textColor=c_cyan,
        spaceAfter=15,
    )

    heading2_style = ParagraphStyle(
        "H2",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=14,
        textColor=c_navy,
        spaceBefore=14,
        spaceAfter=8,
    )

    body_style = ParagraphStyle(
        "Body",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        textColor=c_slate,
        leading=13,
    )

    bold_body = ParagraphStyle(
        "BoldBody",
        parent=body_style,
        fontName="Helvetica-Bold",
        textColor=c_navy,
    )

    elements = []

    # Header / Branding
    elements.append(Paragraph("BotShield Security Assessment", title_style))
    elements.append(Paragraph("Understand. Detect. Defend.", subtitle_style))
    elements.append(HRFlowable(width="100%", thickness=1.5, color=c_cyan, spaceAfter=15))

    # Executive Summary Table
    score_label = f"{score}/100"
    summary_data = [
        [Paragraph("Target Evaluated:", bold_body), Paragraph(target, body_style)],
        [Paragraph("Audit Category:", bold_body), Paragraph(category.capitalize(), body_style)],
        [Paragraph("Security Score / Risk:", bold_body), Paragraph(f"<b>{score_label}</b>", bold_body)],
        [Paragraph("Assessment Timestamp:", bold_body), Paragraph(datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC"), body_style)],
    ]

    for k, v in metadata.items():
        summary_data.append([Paragraph(f"{k}:", bold_body), Paragraph(str(v), body_style)])

    sum_table = Table(summary_data, colWidths=[150, 380])
    sum_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), c_bg_card),
        ("PADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
    ]))
    elements.append(sum_table)
    elements.append(Spacer(1, 15))

    # Findings Section
    elements.append(Paragraph(f"Detailed Findings ({len(findings)})", heading2_style))

    if not findings:
        elements.append(Paragraph("No security deficiencies or anomalies identified.", body_style))
    else:
        for idx, f in enumerate(findings, start=1):
            name = f.get("name") or f.get("indicator") or "Finding"
            sev = (f.get("severity") or "info").upper()
            obs = f.get("observed_value") or f.get("details") or "N/A"
            desc = f.get("description") or ""
            rec = f.get("recommendation") or ""

            # Severity badge colors
            sev_color = colors.HexColor("#0284c7")  # blue
            if sev == "CRITICAL": sev_color = colors.HexColor("#dc2626")  # red
            elif sev == "HIGH": sev_color = colors.HexColor("#ea580c")    # orange
            elif sev == "MEDIUM": sev_color = colors.HexColor("#d97706")  # amber
            elif sev == "LOW": sev_color = colors.HexColor("#ca8a04")     # yellow

            finding_box = [
                [
                    Paragraph(f"<b>{idx}. {name}</b>", bold_body),
                    Paragraph(f"<font color='{sev_color.hexval()}'><b>[{sev}]</b></font>", bold_body)
                ],
                [Paragraph("Observed:", bold_body), Paragraph(obs, body_style)],
            ]
            if desc:
                finding_box.append([Paragraph("Implication:", bold_body), Paragraph(desc, body_style)])
            if rec:
                finding_box.append([Paragraph("Remediation:", bold_body), Paragraph(rec, body_style)])

            f_table = Table(finding_box, colWidths=[110, 420])
            f_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#ffffff")),
                ("PADDING", (0, 0), (-1, -1), 5),
                ("LINEBELOW", (0, -1), (-1, -1), 1, colors.HexColor("#e2e8f0")),
            ]))
            elements.append(f_table)
            elements.append(Spacer(1, 8))

    elements.append(Spacer(1, 15))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#cbd5e1"), spaceAfter=10))

    # Legal Disclaimer
    disclaimer_text = (
        "<b>Notice & Safe Harbor Disclaimer:</b> This report was automatically compiled by the open-source "
        "BotShield platform based strictly on passive network interaction, public response headers, and "
        "authorized telemetry. It does not exploit weaknesses or verify back-end database integrity. "
        "Independent code review and configuration hardening are recommended."
    )
    elements.append(Paragraph(disclaimer_text, ParagraphStyle(
        "Disclaimer",
        parent=body_style,
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor("#64748b")
    )))

    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
